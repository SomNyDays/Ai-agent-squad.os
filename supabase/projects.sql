create table if not exists public.project_tasks (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  created_by uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 160),
  detail text not null default '' check (char_length(detail) <= 5000),
  department text not null default 'Research' check (department in ('Research','Strategy','Engineering','Quality')),
  status text not null default 'Queued' check (status in ('Queued','In progress','In review','Complete')),
  history jsonb not null default '[]'::jsonb check (jsonb_typeof(history) = 'array'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists project_tasks_workspace_updated_idx
  on public.project_tasks(workspace_id, updated_at desc);
create table if not exists public.project_task_events (
  id uuid primary key default gen_random_uuid(),
  task_id bigint not null references public.project_tasks(id) on delete cascade,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  actor_user_id uuid references auth.users(id) on delete set null,
  event_type text not null check (char_length(event_type) between 1 and 64),
  message text not null check (char_length(message) between 1 and 500),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists project_task_events_task_created_idx
  on public.project_task_events(task_id, created_at asc);
alter table public.project_tasks enable row level security;
alter table public.project_task_events enable row level security;
drop policy if exists "workspace members read project tasks" on public.project_tasks;
create policy "workspace members read project tasks" on public.project_tasks
  for select to authenticated using (public.is_workspace_member(workspace_id));
drop policy if exists "workspace members read project task events" on public.project_task_events;
create policy "workspace members read project task events" on public.project_task_events
  for select to authenticated using (public.is_workspace_member(workspace_id));
grant select on public.project_tasks, public.project_task_events to authenticated;
